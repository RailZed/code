-- =====================================================================
-- Конфиг — проблесковые мигалки (blue / red / white)
-- =====================================================================
--
-- Работает через штатный MTA-API addVehicleSirens / setVehicleSirens.
-- На каждую машину можно повесить до 8 точек света. Мы делаем 6 точек:
-- 2 синие (по бокам), 2 красные (по бокам), 2 белые (центр перед/зад).
--
Config = {}

-- ===================================================================
-- На какие модели машин вешать мигалки
-- ===================================================================
-- Перечисли model ID. По умолчанию — стандартные полицейские/FBI/скорая.
-- Если нужно вешать на ВСЕ машины, поставь Config.applyToAll = true.
--
Config.applyToAll = false

Config.vehicleModels = {
    [596] = true,   -- LSPD Police
    [597] = true,   -- SFPD Police
    [598] = true,   -- LVPD Police
    [599] = true,   -- Police Ranger
    [490] = true,   -- FBI Rancher
    [528] = true,   -- FBI Truck
    [416] = true,   -- Ambulance
    [407] = true,   -- Fire Truck
    [544] = true,   -- Fire Truck (ladder)
    [427] = true,   -- Enforcer
}

-- ===================================================================
-- Стиль и поведение сирен
-- ===================================================================
--
-- sirenType:
--   1 — single        2 — dual          3 — twin
--   4 — single small  5 — dual small    6 — twin small
--
-- Для аккуратной "полоски" мигалок берём 2 (dual).
Config.sirenType = 2

-- 360° свечение (видно со всех сторон, а не только спереди)
Config.use360 = true

-- Проверка препятствий (стены гасят свет)
Config.useLOSCheck = true

-- "Дёрганый" режим мигания (быстрый рандом). Обычно — выкл.
Config.useRandomiser = false

-- Без звука сирены (true = тихо). false — играет дефолтная сирена.
Config.silent = false

-- ===================================================================
-- Раскладка лампочек на крыше
-- ===================================================================
--
-- Формат одной точки:
--   { offsetX, offsetY, offsetZ,  R, G, B, A,  minAlpha }
--
-- offset — координаты относительно центра машины (метры).
--   X: -лево / +право
--   Y: -назад / +вперёд
--   Z: 0 центр кузова, ~1.0 — крыша легковушки
-- minAlpha — минимальная видимость когда лампочка "погасла" во время
-- мигания (0 = полностью гаснет).
--
Config.lights = {
    -- передняя ось крыши: синяя слева, красная справа
    { -0.55,  0.40, 0.95,    0,   0, 255, 255,   0 },
    {  0.55,  0.40, 0.95,  255,   0,   0, 255,   0 },

    -- задняя ось крыши: красная слева, синяя справа (зеркало)
    { -0.55, -0.40, 0.95,  255,   0,   0, 255,   0 },
    {  0.55, -0.40, 0.95,    0,   0, 255, 255,   0 },

    -- белые "стробы" по центру: спереди и сзади
    {  0.00,  0.20, 0.98,  255, 255, 255, 255,   0 },
    {  0.00, -0.20, 0.98,  255, 255, 255, 255,   0 },
}

-- ===================================================================
-- Поведение
-- ===================================================================

-- Автоматически вешать сирены на подходящие машины при их создании
Config.autoApply = true

-- Сразу включать мигалки после установки (false — водитель включает сам)
Config.autoTurnOn = false

-- Клавиша для водителя, чтобы переключать мигалки (бинд клиентский)
Config.toggleKey = "lshift"

-- Сообщать в чат при включении/выключении
Config.announce = true

-- Дебаг в /debugscript
Config.debug = false
