-- =====================================================================
-- Emergency lights — конфиг управления
-- =====================================================================
Config = {}

-- ===================================================================
-- Клавиши
-- ===================================================================
-- Каждый бинд переключает один "режим" сигнализации.
-- Режимы и группы лампочек описаны в modes.lua и lights.lua.
--
Config.binds = {
    ["l"]      = "primary",     -- основной режим: красно-синяя гирлянда
    [";"]      = "secondary",   -- белые стробоскопы на крыше
    ["'"]      = "takedown",    -- белый "такдаун" вперёд
    ["lshift"] = "primary",     -- запасной бинд для удобства
}

-- ===================================================================
-- Дистанция рендера и качество
-- ===================================================================
--
-- Корона рисуется только если машина в радиусе maxDrawDistance метров
-- от камеры и попадает на экран. За пределами — пропускаем (FPS).
Config.maxDrawDistance = 250

-- Размер шейдер-короны (drawSize в .fx). 50 — стандарт, 60-80 — ярче,
-- но визуально "размазаннее". Лучше не менять без причины.
Config.shaderDrawSize = 50

-- ===================================================================
-- Поведение
-- ===================================================================

-- Рисовать мигалки и водителю тоже (true) или только окружающим (false).
-- В большинстве ELS-систем своим тоже рисуют, оставим true.
Config.drawForDriver = true

-- Сообщать в чат при вкл/выкл
Config.announce = true

-- Дебаг лог в /debugscript 3
Config.debug = false
