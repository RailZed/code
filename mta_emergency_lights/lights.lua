-- Формат одной лампочки:
--   { {x, y, z}, {r, g, b, a}, size, group [, angleSet] }
--
-- x/y/z — оффсет относительно центра кузова (метры). Положительный y —
-- вперёд, положительный z — вверх, положительный x — вправо.
--
-- group — индекс группы. Режимы в modes.lua указывают какие группы
