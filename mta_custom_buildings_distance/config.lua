-- =====================================================================
-- Конфиг для скрипта дальности кастомных зданий
-- =====================================================================
--
-- Почему ванильные здания было видно далеко, а кастомные — нет:
--
--   Ванильные `building`-элементы — часть мира движка, у них нет
--   индивидуального радиуса стримминга. Их видимость определяется
--   только far clip + LOD distance, которые мы уже подняли.
--
--   А вот `object`-элементы (всё, что создано через createObject
--   или загружено из .map) MTA стримит сам: у каждого свой
--   радиус ~300 юнитов. Дальше этого радиуса объект просто
--   ИСКЛЮЧАЕТСЯ из сцены — никакой far clip ему не поможет.
--
-- Решение: для каждого кастомного `object` зовём
--   setElementStreamable(el, false)
-- что переводит его в «всегда в сцене». Теперь far clip и LOD
-- distance работают так же, как для ванильных зданий.
--
-- Память: каждый объект «всегда в памяти» весит немного (модель уже
-- загружена один раз). Десятки/сотни кастомных зданий — без проблем.
-- Если у тебя ТЫСЯЧИ — можешь выключить forceObjectsAlwaysStreamed
-- и использовать setLowLODElement (см. ниже).
--
Config = {}

-- Главное -----------------------------------------------------------

-- Горизонт камеры. От 300 (ваниль) до 2500.
Config.farClipDistance = 1500

-- Туман. Близко к far clip, чтобы здания не растворялись.
Config.fogDistance = 1400

-- LOD distance кастомных моделей. <= farClipDistance.
Config.modelLODDistance = 1400

-- РЕШАЮЩАЯ опция: для каждого `object`-элемента отключить MTA-стримминг,
-- чтобы он всегда был в сцене (как ванильное здание).
-- Без этого ничего НЕ будет видно дальше ~300 м, какой бы LOD ты не ставил.
Config.forceObjectsAlwaysStreamed = true

-- На какие типы элементов это распространять
Config.target = "object"   -- "object" | "building" | "all"

-- Прочее ------------------------------------------------------------

-- Удерживать far clip и fog (другие ресурсы могут их сбрасывать)
Config.keepFarClipEnforced = true
Config.enforceIntervalMs   = 1000

-- Применить всё при старте + ловить новые объекты на лету
Config.applyOnResourceStart = true
Config.applyOnStreamIn      = true

-- Исключения model ID — НЕ трогать
Config.exclude = {
    -- 1337,
}

-- Дебаг-сообщения в /debugscript 3
Config.debug = false
