-- =====================================================================
-- Конфиг для скрипта дальности кастомных зданий
-- =====================================================================
--
-- Чтобы здания было видно ИЗДАЛЕКА, в MTA нужны ДВЕ вещи одновременно:
--
--   1) Поднять farClipDistance     — горизонт камеры. Без этого движок
--                                    вообще ничего не рисует за ~300 юнитами,
--                                    как бы мы ни выкручивали LOD.
--   2) Поднять modelLODDistance    — у каждой модели свой собственный
--                                    лимит «когда исчезать». Если он
--                                    меньше far clip, объект всё равно
--                                    пропадает.
--
-- Этот скрипт делает и то, и то.
--
-- Как мы НЕ убиваем FPS:
--   * Ванильные здания GTA SA мы НЕ трогаем — у них остаётся стоковый
--     LOD ~170. Значит, даже при огромном far clip большая часть
--     Лос-Сантоса по-прежнему отсекается на 170 юнитах.
--   * Поднимаем LOD distance только у объектов типа `object` — это твои
--     заспавненные кастомные здания. Их обычно немного, FPS почти не
--     просядет даже при дальности 1500.
--   * setFarClipDistance — единственный «дорогой» параметр, но без
--     него физически нельзя увидеть ничего далеко. Подбирай.
--
Config = {}

-- Главные настройки -------------------------------------------------

-- Дистанция отрисовки камеры (горизонт). От 300 (ваниль) до 2500.
-- 1000–1500 — заметно дальше, FPS просядет на 3–10% максимум.
Config.farClipDistance = 1500

-- Дистанция тумана. Туман начинает «выедать» картинку чуть раньше
-- far clip; ставим его около far clip, чтобы здания не растворялись.
Config.fogDistance = 1400

-- LOD distance для каждой кастомной модели. Должен быть <= farClipDistance.
-- Если больше — будет проигнорировано движком.
Config.modelLODDistance = 1400

-- Что брать под управление:
--   "object"   — только объекты (createObject / .map). Рекомендуется.
--   "building" — ванильные здания (НЕ рекомендуется — просадка FPS).
--   "all"      — и то и то.
Config.target = "object"

-- Тонкая настройка --------------------------------------------------

-- Постоянно переустанавливать far clip / fog, потому что некоторые
-- ресурсы (погода, кат-сцены) могут их сбрасывать.
Config.keepFarClipEnforced = true
Config.enforceIntervalMs   = 1000   -- раз в секунду

-- Применять model LOD при старте + при стриминге новых объектов
Config.applyOnResourceStart = true
Config.applyOnStreamIn      = true

-- Исключения: model ID, которые НЕ трогаем
Config.exclude = {
    -- 1337,
}

-- Печатать отладку в дебаг-консоль (F8)
Config.debug = false
