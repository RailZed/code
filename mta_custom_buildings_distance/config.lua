-- =====================================================================
-- Конфиг для скрипта дальности кастомных зданий
-- =====================================================================
--
-- Этот скрипт работает по тому же принципу, что IIYAMA's "lowLOD" —
-- через setLowLODElement: на каждый кастомный object создаётся
-- LOD-клон, и движок рисует именно его, когда основной объект уходит
-- из стримминга. Это ЕДИНСТВЕННЫЙ корректный путь для object'ов
-- (у них собственный стримминг ~300 м, который не лечится far clip'ом).
--
-- Почему IIYAMA жрёт FPS:
--   1) engineSetModelLODDistance = 99000  → LOD рисуется ДО горизонта
--      на всю карту, без отсечения. Тысячи копий в кадре.
--   2) LOD создаётся для каждого object'а, даже для мелких пропов
--      (лампы, заборы, бордюры) — они дают огромный overdraw на дистанции.
--
-- Что я фиксю:
--   1) modelLODDistance = РАЗУМНОЕ значение (1500), а не 99000.
--      На дистанции рисуются только те копии, что попадают в радиус.
--   2) Мелкие/декоративные объекты ПРОПУСКАЮТСЯ (по scale и model ID).
--   3) Прозрачные/невидимые объекты пропускаются.
--   4) Создание LOD идёт через корутину чанками — без фриза при старте.
--
Config = {}

-- Главное -----------------------------------------------------------

-- Горизонт камеры (видимый горизонт). 1500 — оптимум.
Config.farClipDistance = 1500

-- Туман. Чуть ближе к far clip, чтобы здания не «таяли».
Config.fogDistance = 1400

-- LOD distance для моделей. КЛЮЧЕВОЙ параметр FPS!
-- IIYAMA ставит 99000 — это и убивает FPS.
-- 1500 — видно «на горизонт», FPS остаётся хорошим.
Config.modelLODDistance = 1500

-- Фильтры FPS -------------------------------------------------------

-- Не делать LOD-копии для объектов мельче этого scale (мелочёвка
-- незаметна на дистанции, но добавляет overdraw).
Config.minScale = 1.0

-- Если у объекта alpha < 255 (полупрозрачный/невидимый) — пропускать.
Config.skipTransparent = true

-- Не делать LOD для этих model ID (мелкие/тяжёлые пропы).
-- Сюда же добавь свои тяжёлые модели, если они мелкие.
Config.excludeModels = {
    -- 1280-1300 — лампы и фонари (примеры, можно не использовать)
}

-- Поведение ---------------------------------------------------------

-- Удерживать far clip / fog (другие ресурсы их сбрасывают)
Config.keepFarClipEnforced = true
Config.enforceIntervalMs   = 1000

-- На каждый кадр обработки тратим не больше N мс (через корутину)
Config.processBudgetMs = 2

-- Применять при старте + ловить новые ресурсы / объекты
Config.applyOnResourceStart = true
Config.applyOnStreamIn      = true

-- Сообщение в чат при старте (показывает сколько LOD'ов создано)
Config.announceInChat = true

-- Дебаг
Config.debug = false
