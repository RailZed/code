-- =====================================================================
-- Конфиг — режим «по ID»
-- =====================================================================
--
-- Указываешь model ID своих кастомных зданий. Скрипт делает дистанцию
-- ТОЛЬКО для них. Все остальные объекты на карте (лампы, заборы,
-- декор и т.д.) НЕ трогает — поэтому FPS не страдает.
--
Config = {}

-- ===================================================================
-- Главное: список твоих model ID
-- ===================================================================
-- Просто перечисли ID моделей, которые должно быть видно издалека.
-- Один ID = одна твоя модель.
--
-- Пример:
--   Config.models = { 1337, 1338, 1339, 1340 }
--
Config.models = {
    -- 1337,
    -- 1338,
}

-- ===================================================================
-- Горизонт и LOD
-- ===================================================================
--
-- ВАЖНО про farClipDistance:
--   ЭТО ГЛАВНЫЙ FPS-ПАРАМЕТР. Дефолт SA — 300. Каждые +100 заметно
--   бьют по FPS, потому что движок начинает рисовать больше КАРТЫ
--   ВЦЕЛОМ (террейн, воду, машины, пешеходов и т.д.), а не только
--   твои здания.
--
--   Стартуем с компромиссных 500 — это заметно дальше дефолтных 300
--   и при этом не разрывает FPS в клочья. Если хочется ещё дальше —
--   поднимай командой /bfar 600, /bfar 700 и т.д., следя за FPS.
--
--   Если поставить 0 — скрипт вообще не трогает farClipDistance.

Config.farClipDistance = 500
Config.fogDistance     = 450

-- LOD distance именно для твоих моделей. Должен быть <= farClipDistance.
Config.modelLODDistance = 500

-- Удерживать far clip / fog (другие ресурсы могут их сбрасывать).
-- enforceIntervalMs реже = меньше лишней работы каждый кадр-около.
Config.keepFarClipEnforced = true
Config.enforceIntervalMs   = 2000

-- ===================================================================
-- LOD-клоны (главный FPS-параметр после farClipDistance)
-- ===================================================================
--
-- LOD-клоны = на каждое твоё здание создаётся ДОПОЛНИТЕЛЬНЫЙ объект-
-- двойник через createObject + setLowLODElement. В теории движок
-- переключается между оригиналом и клоном по расстоянию, но на
-- практике с большим количеством зданий это удваивает количество
-- элементов в сцене и сильно бьёт по FPS.
--
-- Альтернатива: engineSetModelLODDistance расширяет LOD pipeline
-- для самой модели — движок рисует её издалека БЕЗ доп. объекта.
-- Для большинства карт этого достаточно.
--
-- useLODClones = false  → только engineSetModelLODDistance (лёгкий режим,
--                          но для многих кастомных моделей здания вдалеке
--                          просто не появятся — движок их не рисует без клона)
-- useLODClones = true   → создавать LOD-клоны со streamable=false.
--                          streamable=false критично — без него движок
--                          гоняет стриммер для каждого LOD-клона каждый
--                          кадр (это и было источником просадки FPS).
--
-- По умолчанию true — иначе зданий вдалеке не видно для большинства моделей.
Config.useLODClones = true

-- Делать LOD-клоны не-стримящимися. Должно быть true в 99% случаев.
-- false — только если вдруг RAM критически мало и есть тысячи LOD'ов.
Config.lodNotStreamable = true

-- Не создавать LOD-клон для breakable-объектов (даже если useLODClones=true).
-- Breakable LOD'ы используют attachElements — это пересчёт позиции
-- каждый кадр для каждого LOD'а.
Config.skipBreakableLOD = true

-- ===================================================================
-- Тонкая настройка
-- ===================================================================

-- Применять при старте + ловить новые object'ы на лету
Config.applyOnResourceStart = true
Config.applyOnStreamIn      = true

-- Отчёт в чат после старта (видно сколько LOD'ов создано)
Config.announceInChat = true

-- Дебаг
Config.debug = false
