-- =====================================================================
-- Конфиг для скрипта дальности кастомных зданий
-- =====================================================================
--
-- Скрипт работает АВТОМАТИЧЕСКИ — указывать model ID не нужно.
-- Он сам перебирает все объекты на карте, собирает их model ID
-- и выставляет им увеличенную дистанцию прорисовки.
--
-- Почему так не съест FPS:
--   * setFarClipDistance ловит ВСЁ в кадре — она дорогая, её не трогаем.
--   * engineSetModelLODDistance работает точечно на конкретные модели:
--     движок просто перестаёт скрывать их раньше, остальная карта
--     (деревья, ванильные здания) по-прежнему отсекается на старой
--     дистанции. FPS почти не страдает.
--
-- Безопасные значения LOD: 170 (стандарт SA) ... 500.
--
Config = {}

-- Дистанция прорисовки, которую ставим объектам (в юнитах GTA).
-- 300 — золотая середина (видно сильно дальше, FPS не падает).
-- 500 — для очень больших зданий/мостов/небоскрёбов.
Config.distance = 300

-- Что обрабатывать:
--   "object"   — только объекты, созданные через createObject / .map (рекомендуется)
--   "building" — ванильные здания GTA (НЕ рекомендуется — FPS просядет)
--   "all"      — и то и то
Config.target = "object"

-- Применить дистанцию при старте ресурса
Config.applyOnResourceStart = true

-- Ловить только что заспавненные / попавшие в стриминг объекты
-- и применять LOD к их моделям автоматически.
Config.applyOnStreamIn = true

-- НЕ применять к этим model ID (например, если знаешь, что какие-то
-- объекты ОЧЕНЬ тяжёлые и их лучше оставить с дефолтной дальностью).
-- Пусто = применять ко всему.
Config.exclude = {
    -- 1337,
    -- 1338,
}

-- Печатать отладку (сколько уникальных моделей обработано) в консоль (F8)
Config.debug = false
